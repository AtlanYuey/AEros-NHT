"""Writes Android string resources and L10nKeys.kt from the iOS translations.

Usage: python3 gen_android.py <ios Resources dir> <android res dir> <L10nKeys.kt>
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ios_res, android_res, keys_kt = sys.argv[1:4]

keys = json.load(open(os.path.join(HERE, "keys.json"), encoding="utf-8"))
scope = {}
exec(open(os.path.join(HERE, "android_extra.py"), encoding="utf-8").read(), scope)
extra = scope["EXTRA"]
all_keys = keys + [k for k in extra if k not in keys]

# Android resource folder for each language.
FOLDERS = {
    "ja": "values-ja", "zh-Hans": "values-b+zh+Hans", "zh-Hant": "values-b+zh+Hant",
    "ko": "values-ko", "es": "values-es", "fr": "values-fr", "de": "values-de", "it": "values-it",
    "pt-BR": "values-pt-rBR", "ru": "values-ru", "vi": "values-vi", "th": "values-th", "id": "values-in",
}


def parse_strings(path):
    text = open(path, encoding="utf-8").read()
    pairs = re.findall(r'^"((?:[^"\\]|\\.)*)"\s*=\s*"((?:[^"\\]|\\.)*)";', text, flags=re.M)
    unescape = lambda s: s.replace('\\"', '"').replace("\\n", "\n").replace("\\\\", "\\")
    return {unescape(k): unescape(v) for k, v in pairs}


def translations(lang):
    if lang == "zh-Hans":
        table = parse_strings(os.path.join(ios_res, "zh-Hans.lproj", "Localizable.strings"))
    else:
        s = {}
        exec(open(os.path.join(HERE, f"{lang}.py"), encoding="utf-8").read(), s)
        table = dict(zip(keys, s["T"]))
    for key, langs in extra.items():
        if lang in langs:
            table[key] = langs[lang]
    return table


def android_format(s):
    """iOS specifiers -> Java ones; several arguments become positional."""
    specs = list(re.finditer(r"%(\d\$)?(lld|@|d)", s))
    positional = len(specs) > 1
    out, last = [], 0
    for n, m in enumerate(specs, 1):
        out.append(s[last:m.start()])
        index = m.group(1) or (f"{n}$" if positional else "")
        out.append("%" + index + ("s" if m.group(2) == "@" else "d"))
        last = m.end()
    out.append(s[last:])
    return "".join(out)


def escape(s):
    s = android_format(s)
    s = s.replace("\\", "\\\\").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    s = s.replace('"', '\\"').replace("'", "\\'").replace("\n", "\\n")
    if s.startswith("@") or s.startswith("?"):
        s = "\\" + s
    if s != s.strip():
        s = f'"{s}"'
    return s


def write(folder, table):
    os.makedirs(os.path.join(android_res, folder), exist_ok=True)
    lines = ['<?xml version="1.0" encoding="utf-8"?>', "<resources>"]
    for i, key in enumerate(all_keys):
        if key in table:
            lines.append(f'    <string name="l_{i}">{escape(table[key])}</string>')
    lines.append("</resources>")
    with open(os.path.join(android_res, folder, "strings.xml"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


write("values", {k: k for k in all_keys})
for lang, folder in FOLDERS.items():
    write(folder, translations(lang))

entries = ",\n".join(f'        {json.dumps(k, ensure_ascii=False).replace("$", "\\$")} to R.string.l_{i}' for i, k in enumerate(all_keys))
with open(keys_kt, "w", encoding="utf-8") as f:
    f.write(f"""// Generated by gen_android.py from the iOS translations. Do not edit.
package com.atlanyuey.nhentai.core

import com.atlanyuey.nhentai.R

object L10nKeys {{
    val ids: Map<String, Int> = hashMapOf(
{entries},
    )
}}
""")
print(len(all_keys), "keys,", len(FOLDERS) + 1, "languages")
